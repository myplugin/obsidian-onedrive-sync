// Headless CLI build config (Phase B Milestone 1).
//
// A SEPARATE esbuild config from esbuild.config.mjs (the Obsidian plugin
// build). The plugin build stubs Node builtins (node:url / node:crypto /
// localforage dead-branch) because Obsidian mobile has no Node runtime; the
// CLI build targets Node directly, so it uses REAL Node builtins and MUST NOT
// include those stub plugins (nodeCryptoStubPlugin / nodeUrlStubPlugin /
// localforageScriptStubPlugin).
//
// `obsidian` is NOT external here (unlike the plugin build) — it is resolved
// to ./cli/obsidianStub.ts via the obsidianAliasPlugin below, so the 4
// value-imported symbols (Platform, requireApiVersion, request, requestUrl)
// are satisfied at bundle time.
//
// `window.DEFAULT_ONEDRIVE_CLIENT_ID` / `window.DEFAULT_ONEDRIVE_AUTHORITY`
// are defined (mirroring esbuild.config.mjs): baseTypes.ts:28-29 reads them at
// module load, and Node has no `window` global — without the define, merely
// importing the sync subset (which pulls baseTypes) throws ReferenceError.

import fs from "fs";
import path from "path";
import process from "process";
import esbuild from "esbuild";

const banner = `/*
 * Headless CLI smoke bundle — generated by esbuild.config.cli.mjs.
 * NOT the Obsidian plugin (see esbuild.config.mjs for the plugin build).
 */

// WebWorker-global shim: src/encryptRClone.worker.ts:4 references \`self\`
// (the DedicatedWorkerGlobalScope global) at MODULE TOP-LEVEL, and :186
// calls \`self.addEventListener("message", ...)\`. The plugin build uses
// esbuild-plugin-inline-worker to turn \`.worker\` imports into Blob-URL
// workers (real Worker context → \`self\` + addEventListener exist); the CLI
// build has no such plugin, so the worker module bundles as a regular CJS
// module and \`self\` is undefined in Node → ReferenceError on import.
// Define a minimal stub here (load-time only). For the UNENCRYPTED CLI sync
// (password="") the worker is never invoked for crypto — FakeFsEncrypt
// .isPasswordEmpty()=true → cipherRClone is never constructed
// (fsEncrypt.ts:99-102) — so the stub never participates in actual crypto;
// it only lets the module LOAD. addEventListener is a no-op because no
// real messages arrive (the handler drives crypto, which never runs here).
if (typeof self === "undefined") {
  globalThis.self = { addEventListener: function () {} };
}
`;

console.log(`esbuild version = ${esbuild.version}`);

// Mirror the plugin build's client-id/authority defaults so a clean clone
// builds with no .env. .env (gitignored) overrides for dev/test.
const DEFAULT_ONEDRIVE_CLIENT_ID =
  process.env.ONEDRIVE_CLIENT_ID || "5be03f08-f4bf-406b-9e78-ff6a7d4e7cd4";
const DEFAULT_ONEDRIVE_AUTHORITY =
  process.env.ONEDRIVE_AUTHORITY || "https://login.microsoftonline.com/common";

// Resolve `import ... from "obsidian"` to the local stub. The stub exports
// EXACTLY the 4 symbols the sync-algo subset value-imports; everything else
// the plugin imports from obsidian is `import type` (erased) or loaded only by
// src/main.ts (which the CLI never imports).
function obsidianAliasPlugin() {
  return {
    name: "obsidian-alias",
    setup(build) {
      build.onResolve({ filter: /^obsidian$/ }, () => ({
        path: path.resolve("cli/obsidianStub.ts"),
      }));
    },
  };
}

esbuild
  .build({
    banner: {
      js: banner,
    },
    // Build the five smokes + the Phase C C1b additions: the sync-wiring
    // smoke (cli/sync-wiring-smoke.ts — full 21-arg syncer wiring gate, NO
    // syncer call) and the runnable CLI entry (cli/index.ts → dist/index.js
    // — argv → login/sync/status). entryNames "[name]" yields:
    //   smoke.js / walk-smoke.js / db-smoke.js / assembly-smoke.js /
    //   login-smoke.js / sync-wiring-smoke.js / index.js
    entryPoints: [
      "./cli/smoke.ts",
      "./cli/walk-smoke.ts",
      "./cli/db-smoke.ts",
      "./cli/assembly-smoke.ts",
      "./cli/login-smoke.ts",
      "./cli/sync-wiring-smoke.ts",
      "./cli/index.ts",
    ],
    bundle: true,
    // Node target: use REAL Node builtins (crypto/path/url/fs/http...).
    // Do NOT add the plugin build's node-builtin stub plugins here.
    platform: "node",
    format: "cjs",
    target: "node18",
    logLevel: "info",
    sourcemap: true,
    treeShaking: true,
    outdir: "dist/",
    // esbuild auto-appends the output extension (.js) to entryNames, so
    // "[name]" yields "smoke.js" / "walk-smoke.js". (The contract's literal
    // "[name].js" would double-extend to "smoke.js.js" — deviated to match
    // the contract's INTENT: outputs dist/smoke.js + dist/walk-smoke.js.)
    entryNames: "[name]",
    // baseTypes.ts:28-29 reads window.DEFAULT_* at module load; Node has no
    // window — define replaces the literal token with the string value.
    define: {
      "window.DEFAULT_ONEDRIVE_CLIENT_ID": `"${DEFAULT_ONEDRIVE_CLIENT_ID}"`,
      "window.DEFAULT_ONEDRIVE_AUTHORITY": `"${DEFAULT_ONEDRIVE_AUTHORITY}"`,
    },
    plugins: [obsidianAliasPlugin()],
  })
  .then(() => {
    console.log("CLI build complete -> dist/smoke.js, dist/walk-smoke.js, dist/db-smoke.js, dist/assembly-smoke.js, dist/login-smoke.js, dist/sync-wiring-smoke.js, dist/index.js");
  })
  .catch((err) => {
    console.error(err);
    process.exit(1);
  });

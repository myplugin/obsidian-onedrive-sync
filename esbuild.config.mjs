// Plugin id — read from manifest.json so deploy/reload paths track the id
// automatically (no hardcoded name to forget when the id changes).
const PLUGIN_ID = JSON.parse(fs.readFileSync("manifest.json", "utf8")).id;

// Auto-deploy to Obsidian vault on build/watch (if VAULT_PATH set in .env).
// Mirrors scripts/deploy.mjs and the former webpack DeployPlugin so that
// `npm run dev` (watch) and `npm run build` auto-install the plugin.
function deployPlugin(pluginDir) {
  return {
    name: "deploy",
    setup(build) {
      build.onEnd(() => {
        try {
          if (!fs.existsSync(pluginDir)) {
            fs.mkdirSync(pluginDir, { recursive: true });
          }
          for (const file of ["main.js", "manifest.json", "styles.css"]) {
            const src = path.join(process.cwd(), file);
            if (fs.existsSync(src)) {
              fs.copyFileSync(src, path.join(pluginDir, file));
            }
          }
          console.log(
            `[deploy] main.js + manifest.json + styles.css -> ${pluginDir}`
          );
          reloadPlugin(PLUGIN_ID);
        } catch (e) {
          console.error(`[deploy] failed: ${e.message}`);
        }
      });
    },
  };
}

// Reload the plugin in the running Obsidian instance so deployed changes take
// effect immediately. Uses the `obsidian` CLI (https://help.obsidian.md/cli);
// requires Obsidian to be open. Gracefully no-ops (warning only) when the CLI
// is missing or Obsidian isn't running, so CI / headless builds are unaffected.
function reloadPlugin(pluginId) {
  // Invoke the `obsidian` CLI directly (shell:false). shell:true previously
  // caused a FALSE success — the app launched and exited 0 without actually
  // reloading (Node's shell:true arg concatenation, flagged DEP0190). With
  // shell:false the args pass cleanly; the CLI connects to the running
  // Obsidian and, on success, prints "Reloaded: <id>" to stdout — the honest
  // signal we check (a bare exit-0 is not enough).
  const res = spawnSync("obsidian", ["plugin:reload", `id=${pluginId}`], {
    shell: false,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  const out = (res.stdout || "").trim();
  const ok = out.includes(`Reloaded: ${pluginId}`);
  if (res.error || res.status !== 0 || !ok) {
    const reason = res.error
      ? res.error.code
      : res.status !== 0
        ? `obsidian CLI exit ${res.status}`
        : "obsidian CLI did not confirm reload";
    console.warn(
      `[deploy] plugin reload skipped — ${reason}. Ensure the obsidian CLI is on PATH and Obsidian is running, or toggle the plugin off/on manually.`
    );
    return;
  }
  console.log(`[deploy] reloaded plugin "${pluginId}" in Obsidian.`);
}

// `aggregate-error` -> `clean-stack` imports `node:url` for `fileURLToPath`,
// used only in its `pretty` mode (this plugin never triggers it). On Obsidian
// mobile there's no Node runtime, so a bare `require("node:url")` would fail
// at bundle load. esbuild's `browser` field does not handle the `node:` scheme,
// so intercept it here and resolve to a stub. Matches the effect of webpack's
// `externals: { "node:url": "commonjs2 url" }` redirect (where fileURLToPath is
// effectively absent on the url polyfill too).
function nodeUrlStubPlugin() {
  const STUB = `module.exports = {
  fileURLToPath: (u) => (typeof u === "string" ? u : (u && u.href) || ""),
  pathToFileURL: (p) => ({ href: p, pathname: p }),
  URL: globalThis.URL,
};
`;
  return {
    name: "node-url-stub",
    setup(build) {
      build.onResolve({ filter: /^node:url$/ }, () => ({
        path: "node-url-stub",
        namespace: "node-url-stub",
      }));
      build.onLoad({ filter: /.*/, namespace: "node-url-stub" }, () => ({
        contents: STUB,
        loader: "js",
      }));
    },
  };
}

// msal-node ≥5.1.5 replaced `uuid` with `node:crypto` (for `randomBytes` +
// `createHash` in PKCE generation). The `node:` scheme bypasses esbuild's
// `browser` field (which maps the bare `crypto` → crypto-browserify), so
// intercept `node:crypto` here and redirect to the same polyfill. Matches
// the `node:url` stub pattern above.
function nodeCryptoStubPlugin() {
  return {
    name: "node-crypto-stub",
    setup(build) {
      build.onResolve({ filter: /^node:crypto$/ }, () => ({
        path: "node-crypto-stub",
        namespace: "node-crypto-stub",
      }));
      build.onLoad({ filter: /.*/, namespace: "node-crypto-stub" }, () => ({
        contents: `module.exports = require("crypto-browserify");`,
        loader: "js",
        resolveDir: process.cwd(),
      }));
    },
  };
}

// localforage's dist UMD inlines `lie` -> `immediate` (a macrotask scheduler for
// its Promise polyfill). `immediate` tries MutationObserver -> setImmediate/
// MessageChannel -> `document.createElement('script')` (IE6-8 onreadystatechange
// fallback) -> setTimeout. Obsidian runs on Electron/Chromium (desktop + mobile),
// which always has MutationObserver, so the script-injection branch is DEAD code
// that never executes — but the Obsidian community-directory "code obfuscation"
// check flags its mere presence in main.js. Strip that dead else-if branch at
// onLoad (readable source, not minified output) so the scan target has no
// `createElement('script')`. Deterministic string-replace on version-pinned dist
// bytes => byte-for-byte build-verification stays green. The assertion fails the
// build LOUDLY if a future localforage upgrade reshapes the dist (re-audit then).
// Long-term: migrate localdb.ts off localforage to `idb` (separate refactor).
function localforageScriptStubPlugin() {
  const DEAD_BRANCH = `  } else if ('document' in global && 'onreadystatechange' in global.document.createElement('script')) {
    scheduleDrain = function () {

      // Create a <script> element; its readystatechange event will be fired asynchronously once it is inserted
      // into the document. Do so, thus queuing up the task. Remember to clean up once it's been called.
      var scriptEl = global.document.createElement('script');
      scriptEl.onreadystatechange = function () {
        nextTick();

        scriptEl.onreadystatechange = null;
        scriptEl.parentNode.removeChild(scriptEl);
        scriptEl = null;
      };
      global.document.documentElement.appendChild(scriptEl);
    };
  } else {`;
  const REPLACEMENT = `  } else {`;
  return {
    name: "localforage-script-stub",
    setup(build) {
      build.onLoad(
        {
          filter:
            /[\\/]node_modules[\\/]localforage[\\/]dist[\\/]localforage\.js$/,
        },
        async (args) => {
          let src = await fs.promises.readFile(args.path, "utf8");
          const before = src;
          src = src.replace(DEAD_BRANCH, REPLACEMENT);
          if (src === before) {
            throw new Error(
              `[localforage-script-stub] expected dead createElement('script') branch NOT found in ${args.path}. ` +
                `localforage dist changed — re-audit node_modules/localforage/dist/localforage.js and update DEAD_BRANCH.`
            );
          }
          if (/createElement\(['"]script['"]\)/.test(src)) {
            throw new Error(
              `[localforage-script-stub] createElement('script') still present after patch in ${args.path}.`
            );
          }
          return { contents: src, loader: "js" };
        }
      );
    },
  };
}

